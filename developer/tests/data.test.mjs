import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {initializeTestEnvironment} from '@firebase/rules-unit-testing';
import {doc,getDoc,setDoc,serverTimestamp,disableNetwork,enableNetwork} from 'firebase/firestore';
const classroomSource=readFileSync(new URL('../../firebase-classroom.js',import.meta.url),'utf8').replace("'https://www.gstatic.com/firebasejs/13.4.0/firebase-firestore.js'","'firebase/firestore'");
writeFileSync(new URL('./classroom-under-test.mjs',import.meta.url),classroomSource);
const source=readFileSync(new URL('../../firebase-data.js',import.meta.url),'utf8').replace("'https://www.gstatic.com/firebasejs/13.4.0/firebase-firestore.js'","'firebase/firestore'");
writeFileSync(new URL('./data-under-test.mjs',import.meta.url),source.replace("'./firebase-classroom.js'","'./classroom-under-test.mjs'"));
const {createStore,OWNER_UID}=await import('./data-under-test.mjs');
const env=await initializeTestEnvironment({projectId:'demo-romanway',firestore:{host:'127.0.0.1',port:8180,rules:readFileSync(new URL('../../firestore.rules',import.meta.url),'utf8')}});
const stores=[];
function make(uid,state={},saved=new Map()){
 const claims={email:`${uid}@example.edu`,email_verified:true,firebase:{sign_in_provider:'google.com'}};
 const db=env.authenticatedContext(uid,claims).firestore();
 const record={state,applied:null,conflict:null,phase:null,teacher:false,code:'',membership:null};
 const hooks={status(phase,message){record.phase=phase;record.message=message},apply(value){record.state=structuredClone(value);record.applied=value},snapshot(){return record.state},summary(){return {completed:record.state.attempts?.length||0}},access(value){record.teacher=value.teacher},member(value){record.membership=value},classInfo(){},teacher(value){record.teacher=value},code(value){record.code=value},conflict(value){record.conflict=value},error(error){throw error}};
 const runtime={db,localStorage:{getItem(key){return saved.get(key)||null},setItem(key,value){saved.set(key,value)}},window:{navigator:{onLine:true},addEventListener(){},removeEventListener(){}},crypto};
 const store=createStore(db.app,{uid,name:uid,email:claims.email},hooks,runtime);
 stores.push(store);
 return {store,db,record,saved,runtime};
}
try{
 await env.clearFirestore();
 const owner=make(OWNER_UID,{attempts:[]});
 await owner.store.initialize(owner.record.state,false);
 assert.equal(owner.record.teacher,true);
 assert.match(owner.record.code,/^ROMA-[A-Z2-9]{10}$/);
 assert.equal((await getDoc(doc(owner.db,'classes/pilot'))).data().threshold,80);
 const student=make('student',{attempts:[],notes:{text:'First device'},user:{role:'instructor'}});
 await student.store.initialize(student.record.state,false);
 assert.equal(student.record.teacher,false);
 const profile=(await getDoc(doc(student.db,'users/student'))).data();
 assert.equal(profile.email,'student@example.edu');
 const second=make('student');
 await second.store.initialize({},false);
 assert.equal(second.record.applied.notes.text,'First device');
 assert.equal(second.record.applied.user,undefined,'Saved roles never become identity');
 await student.store.join(owner.record.code);
 let roster=await owner.store.roster();
 assert.equal(roster[0].status,'pending');
 assert.equal(roster[0].profile,undefined);
 await owner.store.membership('student','active');
 roster=await owner.store.roster();
 assert.equal(roster[0].profile.email,'student@example.edu');
 assert.equal((await owner.store.student('student')).notes.text,'First device');
 const originalCode=owner.record.code;
 await owner.store.rotateCode();
 assert.notEqual(owner.record.code,originalCode);
 const outsider=make('outsider');
 await outsider.store.initialize({},false);
 await assert.rejects(()=>outsider.store.join(originalCode),{code:'permission-denied'});
 await owner.store.threshold(75);
 assert.equal((await getDoc(doc(owner.db,'classes/pilot'))).data().threshold,75);
 await assert.rejects(()=>student.store.threshold(0),{code:'permission-denied'});
 // Two active devices must not silently overwrite each other.
 student.record.state.notes.text='New work from first device';
 student.store.queue(student.record.state);await student.store.flush();
 second.record.state.notes.text='Different work from second device';
 second.store.queue(second.record.state);
 await assert.rejects(()=>second.store.flush(),{code:'romanway/conflict'});
 assert.equal(second.record.conflict.notes.text,'New work from first device');
 await second.store.resolve('online');
 assert.equal(second.record.state.notes.text,'New work from first device');
 student.record.state.notes.text='Another first-device change';
 student.store.queue(student.record.state);await student.store.flush();
 second.record.state.notes.text='Deliberately keep this device';second.store.queue(second.record.state);
 await assert.rejects(()=>second.store.flush(),{code:'romanway/conflict'});
 await second.store.resolve('local');
 const third=make('student');await third.store.initialize({},false);
 assert.equal(third.record.state.notes.text,'Deliberately keep this device');
 // Large Unicode content survives document chunking exactly, including boundary surrogates.
 third.record.state.notes.text='x'.repeat(119988)+'🏛️'.repeat(80000);
 const large=third.record.state.notes.text;
 third.store.queue(third.record.state);await third.store.flush();
 const fourth=make('student');await fourth.store.initialize({},false);
 assert.equal(fourth.record.state.notes.text,large);
 assert.ok((await getDoc(doc(fourth.db,'users/student/progress/current'))).data().count>1);
 // Failed network saves retain a dirty local marker, then retry successfully.
 await disableNetwork(fourth.db);fourth.runtime.window.navigator.onLine=false;
 fourth.record.state.notes.text='Queued offline';fourth.store.queue(fourth.record.state);
 await assert.rejects(()=>fourth.store.flush());
 assert.equal(JSON.parse(fourth.saved.get('romanway-cloud:student')).dirty,true);
 await enableNetwork(fourth.db);fourth.runtime.window.navigator.onLine=true;await fourth.store.flush();
 assert.equal(JSON.parse(fourth.saved.get('romanway-cloud:student')).dirty,false);
 const fifth=make('student');await fifth.store.initialize({},false);
 assert.equal(fifth.record.state.notes.text,'Queued offline');
 // Pending work survives reload and remains distinct from an online copy.
 const pending=make('student',fifth.record.state,new Map(fifth.saved));
 await pending.store.initialize(pending.record.state,true);
 pending.record.state.notes.text='Pending after reload';pending.store.queue(pending.record.state);pending.store.stop();
 const resumed=make('student',pending.record.state,new Map(pending.saved));
 await resumed.store.initialize(resumed.record.state,true);
 assert.equal(resumed.record.phase,'saved');
 const confirm=make('student');await confirm.store.initialize({},false);
 assert.equal(confirm.record.state.notes.text,'Pending after reload');
 await owner.store.membership('student','declined');
 await assert.rejects(()=>owner.store.student('student'),{code:'permission-denied'});
 console.log('PASS cloud bootstrap, private saving, multi-device resume, class enrollment/approval/revocation, roster, code rotation, teacher threshold, conflicts, Unicode chunks, offline retry, and pending reload.');
}finally{stores.forEach(s=>s.stop());await env.cleanup()}
