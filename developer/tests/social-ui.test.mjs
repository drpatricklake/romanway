import assert from 'node:assert/strict';
import {harness,action} from './harness.mjs';
const p=harness(process.argv[2]),AR=p.context.__arena.state(),api=p.context.__arena;
const ids=Array.from(api.drawIds('hoplomachus',1,10,Math.random));
const run={ids,res:ids.map(()=>0),cls:'hoplomachus',upto:1,t:1};
const cp={id:'seed',name:'Test checkpoint',upto:1,ids};
const ghost={name:'Nauta',rating:1000,practice:run,ranked:{...run,set:'seed',baseline:true}};
let writes=[],failNext=false;
const snap=d=>({exists:!!d,data:()=>d});
const own={name:'Agricola',furthest:0,mastered:0,done:{},asks:[],replies:[],thanks:[],reports:[],earned:[],hist:[],clients:[]};
const social={user:{id:async()=>'player',canEdit:async()=>false,isOwner:async()=>false},db:{doc(path){return {async get(){return snap(path==='settings/arena'?{cp}:path==='settings/atrium'?{approve:true,ok:{},hidden:{}}:null)},async set(d){if(failNext){failNext=false;throw Object.assign(new Error('Access denied'),{code:'permission-denied'});}writes.push({path,d})},async delete(){}}},collection(path){return {async get(){return {docs:path==='arena'?[{id:'opponent',data:()=>ghost}]:[{id:'player',data:()=>own}]}}}}}};
p.context.RomanWayData={social,queue(){},async flush(){},stop(){}};
p.context.RomanWayAuthApp.setUser({uid:'player',name:'Player',email:'p@example.test'});
const settle=async()=>{for(let i=0;i<6;i++)await new Promise(r=>setImmediate(r));};
action(p,'open-arena');await settle();action(p,'ar-find');await settle();
assert.equal(AR.all[0].id,'opponent');assert.equal(AR.canEdit,false);
action(p,'ar-share',{ });
// The change handler reads checked rather than dataset.
p.model.actions['ar-share']({checked:true});
action(p,'ar-ghost',{i:'0'});await settle();
assert.equal(AR.m.mode,'ghost');assert.deepEqual(Array.from(AR.m.ids),ids);
for(let i=0;i<ids.length;i++){action(p,'ar-ans',{k:String(AR.m.items[i].a)});action(p,'ar-next');}await settle();
assert.equal(AR.m.r,1);assert.ok(writes.some(x=>x.path==='arena/player'));assert.ok(writes.some(x=>x.path==='data/users/player/arena'));
action(p,'ar-menu');action(p,'ar-ranked');await settle();assert.equal(AR.m.mode,'ranked','First unrated seed ghost must bootstrap a rated match');
for(let i=0;i<ids.length;i++){action(p,'ar-ans',{k:String(AR.m.items[i].a)});action(p,'ar-next');}await settle();
assert.ok(p.model.state.arena.ranked.seed);assert.ok(p.model.state.arena.rating>1000);
action(p,'ar-menu');action(p,'ar-ranked');assert.equal(AR.m,null,'The same rated checkpoint cannot be played twice');
action(p,'at-refresh');await settle();assert.equal(p.context.__atriumState.loaded,true);assert.equal(p.context.__atriumState.me,'player');
failNext=true;action(p,'at-reply',{u:'friend',a:'test'});await settle();assert.equal(p.context.__atriumState.err,'permission-denied');
action(p,'at-reply',{u:'friend',a:'test'});await settle();assert.equal(p.context.__atriumState.err,'','Successful retry clears an earlier save error');
p.context.RomanWayAuthApp.setUser(null);assert.equal(p.context.__arena.state().all,null);assert.equal(Object.keys(p.context.__atriumState.docs).length,0);
console.log('PASS Firebase-only UI wiring, exact ghost question replay, shared/private Arena saves, first-seed ranked bootstrap, one rated attempt, Atrium loading, and sign-out cache clearing.');
