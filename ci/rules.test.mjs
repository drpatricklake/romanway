import {readFileSync} from 'node:fs';
import {initializeTestEnvironment,assertSucceeds,assertFails} from '@firebase/rules-unit-testing';
import {doc,getDoc,setDoc,updateDoc,getDocs,collection,serverTimestamp} from 'firebase/firestore';
const root='ZU5goPmM28X40rVridJLtZ9JcBu2';
const env=await initializeTestEnvironment({projectId:'demo-romanway',firestore:{host:'127.0.0.1',port:8180,rules:readFileSync(new URL('../firestore.rules',import.meta.url),'utf8')}});
const identity=uid=>({email:`${uid}@example.edu`,email_verified:true,firebase:{sign_in_provider:'google.com'}});
const db=uid=>env.authenticatedContext(uid,identity(uid)).firestore();
const teacher=db(root),alice=db('alice'),bob=db('bob');
const invite='ROMA-ABCDEFGHJK';
let checks=0;
async function allow(action){await assertSucceeds(action);checks++}
async function deny(action){await assertFails(action);checks++}
const profile=uid=>({uid,email:`${uid}@example.edu`,displayName:uid,summary:{completed:0},updatedAt:serverTimestamp()});
const member=uid=>({uid,email:`${uid}@example.edu`,displayName:uid,status:'pending',inviteCode:invite,requestedAt:serverTimestamp()});
try{
 await env.clearFirestore();
 await deny(getDoc(doc(env.unauthenticatedContext().firestore(),'classes/pilot')));
 await allow(setDoc(doc(teacher,'classes/pilot'),{name:'Pilot',threshold:80}));
 await allow(setDoc(doc(teacher,`classes/pilot/staff/${root}`),{active:true,role:'instructor'}));
 await allow(setDoc(doc(teacher,`classes/pilot/invites/${invite}`),{active:true}));
 await allow(setDoc(doc(alice,'users/alice'),profile('alice')));
 await allow(setDoc(doc(alice,'users/alice/progress/current'),{revision:1,count:1,updatedAt:serverTimestamp()}));
 await allow(setDoc(doc(alice,'users/alice/chunks/000'),{text:'{"attempts":[]}'}));
 await allow(getDoc(doc(alice,'users/alice')));
 await deny(getDoc(doc(bob,'users/alice')));
 await deny(getDoc(doc(teacher,'users/alice')));
 await deny(setDoc(doc(bob,'users/alice'),profile('alice')));
 await deny(getDocs(collection(alice,'users')));
 await deny(updateDoc(doc(alice,'classes/pilot'),{threshold:0}));
 await deny(setDoc(doc(alice,'classes/pilot/staff/alice'),{active:true,role:'instructor'}));
 await deny(setDoc(doc(alice,'classes/pilot/members/alice'),{...member('alice'),status:'active'}));
 await deny(setDoc(doc(alice,'classes/pilot/members/alice'),{...member('alice'),inviteCode:'ROMA-ZZZZZZZZZZ'}));
 await deny(setDoc(doc(alice,'classes/pilot/members/bob'),member('bob')));
 await allow(setDoc(doc(alice,'classes/pilot/members/alice'),member('alice')));
 await deny(updateDoc(doc(alice,'classes/pilot/members/alice'),{status:'active'}));
 await deny(getDoc(doc(teacher,'users/alice/chunks/000')));
 await allow(getDocs(collection(teacher,'classes/pilot/members')));
 await deny(getDocs(collection(alice,'classes/pilot/members')));
 await allow(updateDoc(doc(teacher,'classes/pilot/members/alice'),{status:'active'}));
 await allow(getDoc(doc(teacher,'users/alice')));
 await allow(getDoc(doc(teacher,'users/alice/progress/current')));
 await allow(getDoc(doc(teacher,'users/alice/chunks/000')));
 await deny(setDoc(doc(teacher,'users/alice/chunks/000'),{text:'changed'}));
 await allow(updateDoc(doc(teacher,'classes/pilot/members/alice'),{status:'declined'}));
 await deny(getDoc(doc(teacher,'users/alice')));
 await allow(getDoc(doc(alice,'users/alice')));
 await deny(setDoc(doc(alice,'users/alice'),{...profile('alice'),role:'instructor'}));
 await deny(setDoc(doc(alice,'users/alice'),{...profile('alice'),email:'other@example.edu'}));
 await deny(setDoc(doc(alice,'users/alice/chunks/000'),{text:'x'.repeat(600001)}));
 await deny(setDoc(doc(alice,'users/alice/progress/current'),{revision:2,count:101,updatedAt:serverTimestamp()}));
 await deny(setDoc(doc(alice,'classes/other/members/alice'),member('alice')));
 const unverified=env.authenticatedContext('unverified',{...identity('unverified'),email_verified:false}).firestore();
 await deny(setDoc(doc(unverified,'users/unverified'),profile('unverified')));
 const password=env.authenticatedContext('password',{...identity('password'),firebase:{sign_in_provider:'password'}}).firestore();
 await deny(setDoc(doc(password,'users/password'),profile('password')));
 await allow(setDoc(doc(teacher,'classes/pilot/staff/bob'),{active:true,role:'instructor'}));
 await allow(getDocs(collection(bob,'classes/pilot/members')));
 await allow(updateDoc(doc(teacher,'classes/pilot/staff/bob'),{active:false}));
 await deny(getDocs(collection(bob,'classes/pilot/members')));
 await deny(updateDoc(doc(teacher,'classes/pilot'),{threshold:101}));
 console.log(`PASS ${checks} Firestore permission checks`);
}finally{await env.cleanup()}
